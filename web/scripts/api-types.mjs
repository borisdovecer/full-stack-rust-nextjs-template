// Regenerates src/lib/api/schema.d.ts from the Rust API's OpenAPI document.
// Run after changing a route or a DTO in the API; CI fails when the committed file is stale.
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const web = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const root = resolve(web, "..");
const out = resolve(web, "src/lib/api/schema.d.ts");

const spec = execFileSync("cargo", ["run", "-q", "-p", "app-api", "--", "openapi"], {
  cwd: root,
  encoding: "utf8",
  stdio: ["ignore", "pipe", "inherit"],
});

const ast = await openapiTS(JSON.parse(spec));
const header =
  "// Generated by `npm run api:types` from the Rust API's OpenAPI document. Do not edit.\n\n";
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, header + astToString(ast));
console.log(`wrote ${out}`);
